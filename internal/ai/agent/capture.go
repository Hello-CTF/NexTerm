package agent

import (
	"crypto/hmac"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"

	"github.com/Hello-CTF/NexTerm/internal/ai/memory"
)

// CaptureEventKind discriminates the recorded evidence classes: raw output
// chunks, point-in-time snapshots, timing markers, and human-review boundaries.
type CaptureEventKind string

const (
	CaptureEventOutput   CaptureEventKind = "output"
	CaptureEventSnapshot CaptureEventKind = "snapshot"
	CaptureEventTiming   CaptureEventKind = "timing"
	CaptureEventReview   CaptureEventKind = "review"
)

var (
	// ErrCaptureSealed rejects recordings into a sealed capture.
	ErrCaptureSealed = errors.New("capture 已封存，不能继续记录")
	// ErrCaptureTampered reports a broken hash chain or envelope: the capture
	// was modified after recording, truncated, or never genuine.
	ErrCaptureTampered = errors.New("capture 完整性校验失败")
	// ErrCaptureNotSealed rejects evidence operations (evidence replay,
	// sanitization) on a capture that was never sealed.
	ErrCaptureNotSealed = errors.New("capture 未封存，不能作为证据")
	// ErrCaptureAnchorMissing rejects an evidence operation without the
	// independently held provenance anchor.
	ErrCaptureAnchorMissing = errors.New("capture 缺少独立 provenance anchor")
)

// ProvenanceAnchor is the independently held evidence anchor, generated by
// the seal side and persisted outside the capture (the recorder's trusted
// store). It binds the capture ID, chain head, and envelope hash under the
// recorder's key, so a decoded, truncated, or resealed capture can neither
// mint a valid anchor nor match the original one. A head read from the
// capture being validated is not a trust boundary; this anchor is.
type ProvenanceAnchor struct {
	CaptureID    string `json:"captureId"`
	ChainHead    string `json:"chainHead"`
	EnvelopeHash string `json:"envelopeHash"`
	MAC          string `json:"mac"`
}

func (a *ProvenanceAnchor) sign(key []byte) string {
	mac := hmac.New(sha256.New, key)
	mac.Write([]byte(a.CaptureID + "\x00" + a.ChainHead + "\x00" + a.EnvelopeHash))
	return hex.EncodeToString(mac.Sum(nil))
}

// CaptureEvent is one recorded evidence item. AtMS is relative to the capture
// start (deterministic: the recorder supplies it, never a wall clock).
// PrevHash/Hash form the integrity chain computed over the canonical payload;
// Data is raw bytes (JSON base64) so arbitrary output survives byte-exactly.
type CaptureEvent struct {
	Seq        uint64           `json:"seq"`
	Kind       CaptureEventKind `json:"kind"`
	AtMS       int64            `json:"atMs"`
	Stream     string           `json:"stream,omitempty"`
	Data       []byte           `json:"data,omitempty"`
	Name       string           `json:"name,omitempty"`
	DurationMS int64            `json:"durationMs,omitempty"`
	Redacted   bool             `json:"redacted,omitempty"`
	PrevHash   string           `json:"prevHash"`
	Hash       string           `json:"hash"`
}

func (e CaptureEvent) payload(prev string) []byte {
	// nil and empty data are the same evidence and must hash identically:
	// JSON omitempty drops both, so the hashed representation canonicalizes
	// nil to empty and survives JSON round-trips.
	data := e.Data
	if data == nil {
		data = []byte{}
	}
	encoded, _ := json.Marshal(struct {
		Seq        uint64           `json:"seq"`
		Kind       CaptureEventKind `json:"kind"`
		AtMS       int64            `json:"atMs"`
		Stream     string           `json:"stream"`
		Data       []byte           `json:"data"`
		Name       string           `json:"name"`
		DurationMS int64            `json:"durationMs"`
		Redacted   bool             `json:"redacted"`
		Prev       string           `json:"prev"`
	}{e.Seq, e.Kind, e.AtMS, e.Stream, data, e.Name, e.DurationMS, e.Redacted, prev})
	return encoded
}

func (e CaptureEvent) seal(prev string) CaptureEvent {
	e.PrevHash = prev
	sum := sha256.Sum256(e.payload(prev))
	e.Hash = hex.EncodeToString(sum[:])
	return e
}

// Capture is a verifiable recording of an agent run's observable activity for
// human review. The zero value is not ready; use NewCapture.
//
// Integrity model: every event is hash-chained, and Seal binds the evidence
// metadata (ID, conversation, job, start), the seal state, the chain head,
// and the sanitized-source provenance into EnvelopeHash, then issues the
// ProvenanceAnchor under the recorder's key. Verify checks self-consistency;
// the evidence boundary is the independently held anchor: Replay and
// Sanitize require it, so a decoded, truncated, or resealed capture without
// the recorder's key cannot produce evidence. Unsealed captures stay on the
// explicitly non-evidence PreviewReplay path.
type Capture struct {
	ID              string         `json:"id"`
	ConversationID  string         `json:"conversationId,omitempty"`
	JobID           string         `json:"jobId,omitempty"`
	StartedAt       int64          `json:"startedAt"`
	Sealed          bool           `json:"sealed"`
	ChainHead       string         `json:"chainHead,omitempty"`
	EnvelopeHash    string         `json:"envelopeHash,omitempty"`
	SourceChainHead string         `json:"sourceChainHead,omitempty"`
	Events          []CaptureEvent `json:"events"`

	// everSealed is the non-resealable boundary: it survives field-level
	// mutation of a copied capture, so clearing Sealed cannot re-arm Seal.
	everSealed bool

	// trusted marks a capture produced by the trusted signer's recording
	// path. It is lost on JSON decoding, so decoded or otherwise untrusted
	// captures cannot be re-issued through the signer.
	trusted bool
}

// NewCapture starts a capture anchored at the given wall-clock start; every
// event timestamp is a caller-supplied relative offset, keeping replays
// deterministic.
func NewCapture(id, conversationID, jobID string, startedAt int64) *Capture {
	return &Capture{ID: id, ConversationID: conversationID, JobID: jobID, StartedAt: startedAt, Events: []CaptureEvent{}}
}

func (c *Capture) append(event CaptureEvent) error {
	if c.Sealed {
		return ErrCaptureSealed
	}
	event.Seq = uint64(len(c.Events)) + 1
	prev := ""
	if len(c.Events) > 0 {
		prev = c.Events[len(c.Events)-1].Hash
	}
	c.Events = append(c.Events, event.seal(prev))
	return nil
}

// RecordOutput appends a raw output chunk (stdout or stderr as recorded).
func (c *Capture) RecordOutput(atMS int64, stream string, data []byte) error {
	return c.append(CaptureEvent{Kind: CaptureEventOutput, AtMS: atMS, Stream: stream, Data: data})
}

// RecordSnapshot appends a point-in-time state snapshot.
func (c *Capture) RecordSnapshot(atMS int64, data []byte) error {
	return c.append(CaptureEvent{Kind: CaptureEventSnapshot, AtMS: atMS, Data: data})
}

// RecordTiming appends a named timing marker.
func (c *Capture) RecordTiming(atMS int64, name string, durationMS int64) error {
	return c.append(CaptureEvent{Kind: CaptureEventTiming, AtMS: atMS, Name: name, DurationMS: durationMS})
}

// RecordReviewBoundary appends a human-review boundary: a gate where a person
// must decide before the recorded flow may proceed.
func (c *Capture) RecordReviewBoundary(atMS int64, gate string) error {
	return c.append(CaptureEvent{Kind: CaptureEventReview, AtMS: atMS, Name: gate})
}

// seal freezes the capture and issues the provenance anchor under the
// recorder's key. Sealing is a non-resealable boundary: a capture that was
// ever sealed cannot be sealed again. It is unexported: only the trusted
// EvidenceSigner seals, so no evidence caller can self-issue provenance.
func (c *Capture) seal(key []byte) (*ProvenanceAnchor, error) {
	if c.everSealed || c.Sealed {
		return nil, ErrCaptureSealed
	}
	if len(key) == 0 {
		return nil, errors.New("capture 封存密钥不能为空")
	}
	if len(c.Events) == 0 {
		// A legitimately empty capture (empty answer, no tool calls) gets
		// a deterministic lifecycle marker so the sealed chain is anchored
		// and replayable. It records no assistant content.
		if err := c.RecordTiming(0, "lifecycle", 0); err != nil {
			return nil, err
		}
	}
	c.Sealed = true
	c.everSealed = true
	c.ChainHead = c.chainHead()
	c.EnvelopeHash = c.envelopeHash()
	anchor := &ProvenanceAnchor{CaptureID: c.ID, ChainHead: c.ChainHead, EnvelopeHash: c.EnvelopeHash}
	anchor.MAC = anchor.sign(key)
	return anchor, nil
}

// verifyAnchor checks the independently held provenance anchor against the
// capture with the recorder's key: the MAC must be valid and every anchored
// field must match the capture. A nil anchor, a wrong key, or a capture
// whose content moved away from the anchor all fail closed.
func (c *Capture) verifyAnchor(key []byte, anchor *ProvenanceAnchor) error {
	if anchor == nil {
		return fmt.Errorf("%w: %v", ErrCaptureAnchorMissing, "anchor is nil")
	}
	if len(key) == 0 {
		return errors.New("capture 验证密钥不能为空")
	}
	if !hmac.Equal([]byte(anchor.MAC), []byte(anchor.sign(key))) {
		return fmt.Errorf("%w: provenance anchor MAC 无效", ErrCaptureTampered)
	}
	if anchor.CaptureID != c.ID || anchor.ChainHead != c.ChainHead || anchor.EnvelopeHash != c.EnvelopeHash {
		return fmt.Errorf("%w: provenance anchor 与 capture 不匹配", ErrCaptureTampered)
	}
	return c.Verify()
}

func (c *Capture) chainHead() string {
	if len(c.Events) == 0 {
		return ""
	}
	return c.Events[len(c.Events)-1].Hash
}

func (c *Capture) envelopeHash() string {
	sum := sha256.Sum256([]byte(c.envelopePayload()))
	return hex.EncodeToString(sum[:])
}

func (c *Capture) envelopePayload() string {
	encoded, _ := json.Marshal(struct {
		ID              string `json:"id"`
		ConversationID  string `json:"conversationId"`
		JobID           string `json:"jobId"`
		StartedAt       int64  `json:"startedAt"`
		Sealed          bool   `json:"sealed"`
		ChainHead       string `json:"chainHead"`
		SourceChainHead string `json:"sourceChainHead"`
	}{c.ID, c.ConversationID, c.JobID, c.StartedAt, c.Sealed, c.ChainHead, c.SourceChainHead})
	return string(encoded)
}

// RequiresReview reports whether the capture contains any human-review boundary.
func (c *Capture) RequiresReview() bool {
	for _, event := range c.Events {
		if event.Kind == CaptureEventReview {
			return true
		}
	}
	return false
}

// ReviewGates lists the human-review boundary names in recorded order.
func (c *Capture) ReviewGates() []string {
	gates := []string{}
	for _, event := range c.Events {
		if event.Kind == CaptureEventReview {
			gates = append(gates, event.Name)
		}
	}
	return gates
}

// Verify recomputes the hash chain and the evidence envelope, reporting the
// first inconsistency: tampering, truncation, or metadata alteration of a
// sealed capture is detected. A capture resealed after truncation is a new
// self-consistent value, so Verify alone cannot judge it, that boundary is
// enforced by Sanitize's provenance requirement.
func (c *Capture) Verify() error {
	prev := ""
	for index, event := range c.Events {
		if event.Seq != uint64(index)+1 {
			return fmt.Errorf("%w: seq %d at position %d", ErrCaptureTampered, event.Seq, index)
		}
		if event.PrevHash != prev {
			return fmt.Errorf("%w: prev hash mismatch at seq %d", ErrCaptureTampered, event.Seq)
		}
		if event.seal(prev).Hash != event.Hash {
			return fmt.Errorf("%w: hash mismatch at seq %d", ErrCaptureTampered, event.Seq)
		}
		prev = event.Hash
	}
	if c.Sealed && c.ChainHead == "" {
		return fmt.Errorf("%w: sealed without a chain head", ErrCaptureTampered)
	}
	if c.ChainHead != "" && prev != c.ChainHead {
		return fmt.Errorf("%w: chain head mismatch (truncated or resealed)", ErrCaptureTampered)
	}
	if c.Sealed && c.EnvelopeHash == "" {
		return fmt.Errorf("%w: sealed without an envelope", ErrCaptureTampered)
	}
	if c.EnvelopeHash != "" && c.envelopeHash() != c.EnvelopeHash {
		return fmt.Errorf("%w: envelope mismatch (metadata, seal state, chain head, or provenance altered)", ErrCaptureTampered)
	}
	return nil
}

// replayAnchored is the evidence replay: it requires a sealed capture and
// the independently held provenance anchor issued at seal time, and
// returns the events in recorded order. A decoded or forged capture
// without a valid anchor is refused.
func (c *Capture) replayAnchored(key []byte, anchor *ProvenanceAnchor) ([]CaptureEvent, error) {
	if !c.Sealed {
		return nil, ErrCaptureNotSealed
	}
	if err := c.verifyAnchor(key, anchor); err != nil {
		return nil, err
	}
	events := make([]CaptureEvent, len(c.Events))
	copy(events, c.Events)
	return events, nil
}

// PreviewReplay replays a live, unsealed capture for inspection while it is
// still being recorded. The result is explicitly not evidence: only a sealed,
// envelope-verified capture (see Replay) can back human review.
func (c *Capture) PreviewReplay() ([]CaptureEvent, error) {
	if c.Sealed {
		return nil, fmt.Errorf("%w: sealed captures must use Replay", ErrCaptureSealed)
	}
	if err := c.Verify(); err != nil {
		return nil, err
	}
	events := make([]CaptureEvent, len(c.Events))
	copy(events, c.Events)
	return events, nil
}

// sanitizeAnchored returns a sealed redacted copy for human review: raw
// output and snapshot data pass through the memory redactor, timing and
// review boundaries are preserved, the copy carries its own valid chain
// and envelope, and SourceChainHead anchors it to the original's chain
// head. The sanitized copy's own anchor is returned alongside it.
//
// Evidence operations require the independently held provenance anchor
// issued at seal time: sanitization refuses a capture whose complete
// provenance cannot be verified, so removed review gates can never be
// laundered into a review copy.
func (c *Capture) sanitizeAnchored(key []byte, anchor *ProvenanceAnchor) (*Capture, *ProvenanceAnchor, error) {
	if !c.Sealed {
		return nil, nil, ErrCaptureNotSealed
	}
	if c.SourceChainHead != "" {
		// A sanitized copy is a terminal review artifact: re-sanitizing it
		// would produce a second envelope for the same anchor key and
		// orphan the persisted one.
		return nil, nil, ErrCaptureAlreadySanitized
	}
	if err := c.verifyAnchor(key, anchor); err != nil {
		return nil, nil, err
	}
	sanitized := &Capture{
		ID: c.ID + "#sanitized", ConversationID: c.ConversationID, JobID: c.JobID,
		StartedAt: c.StartedAt, Sealed: true, everSealed: true,
		SourceChainHead: c.ChainHead,
		Events:          make([]CaptureEvent, 0, len(c.Events)),
	}
	prev := ""
	for _, event := range c.Events {
		redacted, changed := memory.RedactText(string(event.Data))
		event.Data = []byte(redacted)
		event.Redacted = event.Redacted || changed
		event = event.seal(prev)
		prev = event.Hash
		sanitized.Events = append(sanitized.Events, event)
	}
	sanitized.ChainHead = sanitized.chainHead()
	sanitized.EnvelopeHash = sanitized.envelopeHash()
	sanitizedAnchor := &ProvenanceAnchor{CaptureID: sanitized.ID, ChainHead: sanitized.ChainHead, EnvelopeHash: sanitized.EnvelopeHash}
	sanitizedAnchor.MAC = sanitizedAnchor.sign(key)
	return sanitized, sanitizedAnchor, nil
}
