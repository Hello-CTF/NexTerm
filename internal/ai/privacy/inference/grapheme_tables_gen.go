//go:build ignore

// Generates grapheme_tables.go from the tables.rs of the unicode-segmentation
// crate version that HF tokenizers 0.23.1 used, so grapheme clusters match.
//
//	go run grapheme_tables_gen.go <unicode-segmentation-1.13.3>/src/tables.rs
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

func block(source, start string) string {
	index := strings.Index(source, start)
	if index < 0 {
		panic("missing " + start)
	}
	rest := source[index+len(start):]
	return strings.Join(strings.Fields(rest[:strings.Index(rest, "];")]), " ")
}

func main() {
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	source := string(data)
	if !strings.Contains(source, "pub const UNICODE_VERSION: (u64, u64, u64) = (17, 0, 0);") {
		panic("unexpected Unicode version")
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by grapheme_tables_gen.go from unicode-segmentation 1.13.3 (Unicode 17.0.0); DO NOT EDIT.\n\npackage inference\n\n")
	triple := regexp.MustCompile(`\('\\u\{([0-9a-f]+)\}', '\\u\{([0-9a-f]+)\}', GC_(\w+)\)`)
	out.WriteString("var graphemeCategoryTable = []graphemeRange{\n")
	for _, m := range triple.FindAllStringSubmatch(block(source, "const grapheme_cat_table: &[(char, char, GraphemeCat)] = &["), -1) {
		fmt.Fprintf(&out, "{0x%s, 0x%s, gc%s},\n", m[1], m[2], strings.ReplaceAll(m[3], "_", ""))
	}
	out.WriteString("}\n\n")
	pair := regexp.MustCompile(`\('\\u\{([0-9a-f]+)\}', '\\u\{([0-9a-f]+)\}'\)`)
	out.WriteString("var incbExtendTable = [][2]rune{\n")
	for _, m := range pair.FindAllStringSubmatch(block(source, "const InCB_Extend_table: &[(char, char)] = &["), -1) {
		fmt.Fprintf(&out, "{0x%s, 0x%s},\n", m[1], m[2])
	}
	out.WriteString("}\n\n")
	linker := source[strings.Index(source, "pub fn is_incb_linker"):]
	linker = linker[:strings.Index(linker, "}\n")]
	out.WriteString("var incbLinkers = []rune{")
	for _, m := range regexp.MustCompile(`'\\u\{([0-9A-Fa-f]+)\}'`).FindAllStringSubmatch(linker, -1) {
		fmt.Fprintf(&out, "0x%s, ", strings.ToLower(m[1]))
	}
	out.WriteString("}\n")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("grapheme_tables.go", formatted, 0o644); err != nil {
		panic(err)
	}
}
