const cliTimeout = 30 * time.Second

var (
	cliNewManager = func(getenv func(string) string) ServiceManager {
		return NewServiceManagerWithPrefix(runtime.GOOS, nil, getenv, mustHomeDir(), cliServicePrefix)
	}
	cliRuntimeFactory = func(store *Store, dataDir string, prober *Prober, manager ServiceManager) (*Runtime, error) {
		return New(Options{Store: store, DataDir: dataDir, Prober: prober, Manager: manager})
	}
	// PurposeHandlerWirer is called by cliRun right after the runtime is built so the composition root can register
	// non-terminal bridge purpose handlers; the servers live in internal/fleet/agent/purpose, which imports this
	// package, so they cannot be wired from here.
	PurposeHandlerWirer func(r *Runtime)

	// cliServicePrefix is set by RunCLIWithServicePrefix: embedded distributions (e.g. the nexterm-server
	// agent subcommand) generate service commands with a subcommand prefix; the standalone nexterm-agent always leaves it empty.
	cliServicePrefix []string
)

// RunCLI executes the device agent subcommands (enroll, run, install,
// uninstall, status) and returns the process exit code. The same-binary
// wiring (for example `nexterm-desktop agent ...`) calls this entrypoint.
func RunCLI(args []string, getenv func(string) string, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		printCLIUsage(stderr)
		return ExitUsage
	}
	if getenv == nil {
		getenv = func(string) string { return "" }
	}
	command, rest := args[0], args[1:]
	switch command {
	case "enroll":
		return cliEnroll(rest, getenv, stdout, stderr)
	case "run":
		return cliRun(rest, getenv, stdout, stderr)
	case "install":
		return cliInstall(rest, getenv, stdout, stderr)
	case "uninstall":
		return cliUninstall(rest, getenv, stdout, stderr)
	case "status":
		return cliStatus(rest, getenv, stdout, stderr)
	case "update", "upgrade":
		return cliUpdate(rest, getenv, stdout, stderr)
	case "version":
		fmt.Fprintln(stdout, version.Version)
		return 0
	default:
		fmt.Fprintf(stderr, "agent: 未知子命令 %q\n", applog.RedactText(command))
		printCLIUsage(stderr)
		return ExitUsage
	}
}

// RunCLIWithServicePrefix is the same as RunCLI, except the service commands generated by install and runtime
// autostart repair insert servicePrefix between the executable and run: the nexterm-server embedded distribution passes
// ["agent"], so the service runs `<server> agent run --data-dir ...`; the standalone nexterm-agent
// goes through RunCLI, and the service runs `<agent> run --data-dir ...`.
func RunCLIWithServicePrefix(args []string, servicePrefix []string, getenv func(string) string, stdout, stderr io.Writer) int {
	previous := cliServicePrefix
	cliServicePrefix = servicePrefix
	defer func() { cliServicePrefix = previous }()
	return RunCLI(args, getenv, stdout, stderr)
}

func printCLIUsage(stderr io.Writer) {
	fmt.Fprintln(stderr, "用法：agent <enroll|run|install|uninstall|status|update|version> [选项]")
	fmt.Fprintln(stderr, "  update|upgrade [--version <版本>] [--yes|-y] [--force|-f] [--check]  从官方 release 升级已安装的设备代理")
}

func newFlagSet(name string, stderr io.Writer) *flag.FlagSet {
	set := flag.NewFlagSet(name, flag.ContinueOnError)
	set.SetOutput(redactingCLIWriter{next: stderr})
	return set
}

type redactingCLIWriter struct{ next io.Writer }

func (writer redactingCLIWriter) Write(input []byte) (int, error) {
	output := applog.RedactText(string(input))
	written, err := io.WriteString(writer.next, output)
	if err != nil {
		return 0, err
	}
	if written != len(output) {
		return 0, io.ErrShortWrite
	}
	return len(input), nil
}

func resolveDataDir(flagValue string, getenv func(string) string) (string, error) {
	if flagValue != "" {
		return flagValue, nil
	}
	if value := getenv("NEXTERM_DATA_DIR"); value != "" {
		return value, nil
	}
	return "", errors.New("请指定 --data-dir 或设置 NEXTERM_DATA_DIR")
}

func cliEnroll(args []string, getenv func(string) string, stdout, stderr io.Writer) int {
	set := newFlagSet("enroll", stderr)
	server := set.String("server", "", "服务器地址（必填）")
	code := set.String("code", "", "设备注册码（必填）")
	name := set.String("name", "", "设备名（默认为主机名）")
	dataDir := set.String("data-dir", "", "数据目录（默认为 NEXTERM_DATA_DIR）")
	insecure := set.Bool("insecure", false, "跳过 TLS 证书校验（仅用于受信任的自签名服务器）")
	if err := set.Parse(args); err != nil {
		return ExitUsage
	}
	if *server == "" || *code == "" {
		fmt.Fprintln(stderr, "agent enroll: 必须指定 --server 与 --code")
		return ExitUsage
	}
	dir, err := resolveDataDir(*dataDir, getenv)
	if err != nil {
		printCLIError(stderr, "agent enroll:", err)
		return ExitUsage
	}
	deviceName := *name
	if deviceName == "" {
		if hostname, err := os.Hostname(); err == nil {
			deviceName = hostname
		}
	}
	client, err := NewEndpointClient(BaseURLEntry{URL: *server, Insecure: *insecure})
	if err != nil {
		printCLIError(stderr, "agent enroll:", err)
		return ExitError
	}
	ctx, cancel := context.WithTimeout(context.Background(), cliTimeout)
	defer cancel()
	response, err := client.Enroll(ctx, EnrollRequest{
		Code:       *code,
		Name:       deviceName,
		Platform:   runtime.GOOS,
		AppVersion: version.Version,
	})
	if err != nil {
		printServerError(stderr, "注册失败", err)
		return ExitError
	}
	config := &Config{
		Version:           configVersion,
		DeviceID:          response.DeviceID,
		Secret:            response.Secret,
		Name:              deviceName,
		Platform:          runtime.GOOS,
		AppVersion:        version.Version,
		BaseURLs:          response.BaseURLs,
		MetricsIntervalMS: clampMetricsInterval(response.MetricsIntervalMS),
		DesiredAutostart:  response.DesiredAutostart,
		TerminalEnabled:   response.TerminalEnabled,
		EnrolledAt:        ids.NowMS(),
	}
	if len(config.BaseURLs) == 0 {
		fmt.Fprintln(stderr, "agent enroll: 服务器未返回任何接入地址")
		return ExitError
	}
	store := StoreAt(dir)
	if err := store.Save(config); err != nil {
		printCLIError(stderr, "agent enroll:", err)
		return ExitError
	}
	fmt.Fprintf(stdout, "注册成功：device_id=%s name=%s base_urls=%d metrics_interval=%ds desired_autostart=%t terminal=%s\n",
		config.DeviceID, config.Name, len(config.BaseURLs), config.MetricsIntervalMS/1000, config.DesiredAutostart, enabledText(config.TerminalEnabled))
	fmt.Fprintf(stdout, "配置已写入 %s (0600)\n", store.Path())
	return ExitOK
}

func cliRun(args []string, getenv func(string) string, stdout, stderr io.Writer) int {
	set := newFlagSet("run", stderr)
	dataDir := set.String("data-dir", "", "数据目录（默认为 NEXTERM_DATA_DIR）")
	pprofAddr := set.String("pprof-addr", "", "pprof 监听地址（默认为 NEXTERM_PPROF_ADDR；仅限回环地址，显式指定 0.0.0.0 除外）")
	if err := set.Parse(args); err != nil {
		return ExitUsage
	}
	dir, err := resolveDataDir(*dataDir, getenv)
	if err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitUsage
	}
	if _, err := pprof.NormalizeAddr(pprof.ResolveAddr(*pprofAddr, getenv)); err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitUsage
	}
	useDataDirShell(dir)
	shellenv.Default().Start()
	if err := os.MkdirAll(filepath.Join(dir, "fleet"), 0o700); err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitError
	}
	unlock, err := acquireLock(filepath.Join(dir, "fleet", "agent.lock"))
	if errors.Is(err, errLockBusy) {
		fmt.Fprintln(stdout, "已有另一个设备代理实例正在运行，本实例已退出")
		return ExitOK
	}
	if err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitError
	}
	defer unlock()
	logger := slog.New(applog.NewRedactingHandler(slog.NewTextHandler(stderr, nil)))
	previousLogger := slog.Default()
	slog.SetDefault(logger)
	defer slog.SetDefault(previousLogger)
	pprofServer, err := pprof.Start(logger, pprof.ResolveAddr(*pprofAddr, getenv))
	if err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitError
	}
	defer func() {
		shutdownCtx, shutdownCancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer shutdownCancel()
		_ = pprofServer.Close(shutdownCtx)
	}()
	store := StoreAt(dir)
	config, err := store.Load()
	if errors.Is(err, ErrNotEnrolled) {
		fmt.Fprintln(stderr, "agent run: 设备未注册，请先执行 agent enroll")
		return ExitError
	}
	if err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitError
	}
	prober, err := NewProber(config.BaseURLs)
	if err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitError
	}
	agentRuntime, err := cliRuntimeFactory(store, dir, prober, cliNewManager(getenv))
	if err != nil {
		printCLIError(stderr, "agent run:", err)
		return ExitError
	}
	if PurposeHandlerWirer != nil {
		PurposeHandlerWirer(agentRuntime)
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	fmt.Fprintf(stdout, "设备代理运行中：device_id=%s name=%s\n", config.DeviceID, config.Name)
	err = agentRuntime.Run(ctx)
	switch {
	case err == nil:
		return ExitOK
	case errors.Is(err, errUpgradeStaged):
		fmt.Fprintln(stdout, "agent: 协议版本不兼容，已下载并校验新版本，稍后将自动完成替换并启动服务")
		return ExitOK
	case errors.Is(err, ErrRevoked):
		fmt.Fprintln(stderr, "agent: 设备已被吊销，已停止运行；如需重新接入，请执行 agent enroll")
		return ExitRevoked
	case errors.Is(err, ErrProtocolMismatch):
		fmt.Fprintln(stderr, "agent: 控制通道协议版本不兼容，且自动升级不可用或已失败；请执行 agent update --force，或使用 install-device.sh 重新安装")
		return ExitProtocol
	default:
		printCLIError(stderr, "agent run:", err)
		return ExitError
	}
}

func cliInstall(args []string, getenv func(string) string, stdout, stderr io.Writer) int {
	return cliServiceChange("install", args, getenv, stdout, stderr, func(ctx context.Context, manager ServiceManager, executable, dataDir string) error {
		return manager.Install(ctx, executable, dataDir)
	})
}

func cliUninstall(args []string, getenv func(string) string, stdout, stderr io.Writer) int {
	return cliServiceChange("uninstall", args, getenv, stdout, stderr, func(ctx context.Context, manager ServiceManager, _, _ string) error {
		return manager.Uninstall(ctx)
	})
}

func cliServiceChange(command string, args []string, getenv func(string) string, stdout, stderr io.Writer, action func(context.Context, ServiceManager, string, string) error) int {
	set := newFlagSet(command, stderr)
	dataDir := set.String("data-dir", "", "数据目录（可选；默认使用标准位置，也可通过 NEXTERM_DATA_DIR 指定）")
	shell := set.String("shell", "", "终端使用的 shell 绝对路径（仅 install 使用；auto 表示清除设置，改用账户登录 shell）")
	if err := set.Parse(args); err != nil {
		return ExitUsage
	}
	dir, err := resolveDataDir(*dataDir, getenv)
	if err != nil {
		printCLIError(stderr, "agent "+command+":", err)
		return ExitUsage
	}
	if *shell != "" && command != "install" {
		fmt.Fprintf(stderr, "agent %s: --shell 仅适用于 install\n", command)
		return ExitUsage
	}
	if message, err := applyShellFlag(dir, *shell); err != nil {
		printCLIError(stderr, "agent "+command+":", err)
		return ExitUsage
	} else if message != "" {
		fmt.Fprintln(stdout, message)
	}
	executable, err := os.Executable()
	if err != nil {
		printCLIError(stderr, "agent "+command+":", err)
		return ExitError
	}
	manager := cliNewManager(getenv)
	ctx, cancel := context.WithTimeout(context.Background(), cliTimeout)
	defer cancel()
	if err := action(ctx, manager, executable, dir); err != nil {
		printCLIError(stderr, "agent "+command+":", err)
		return ExitError
	}
	status := manager.Status(ctx)
	fmt.Fprintf(stdout, "%s 完成：installed=%t enabled=%t active=%t\n", command, status.Installed, status.Enabled, status.Active)
	if status.LastError != "" {
		fmt.Fprintf(stdout, "注意：%s\n", applog.RedactText(status.LastError))
	}
	printServiceEnvironment(stdout, manager)
	return ExitOK
}

func cliStatus(args []string, getenv func(string) string, stdout, stderr io.Writer) int {
	set := newFlagSet("status", stderr)
	dataDir := set.String("data-dir", "", "数据目录（默认为 NEXTERM_DATA_DIR）")
	if err := set.Parse(args); err != nil {
		return ExitUsage
	}
	dir, err := resolveDataDir(*dataDir, getenv)
	if err != nil {
		printCLIError(stderr, "agent status:", err)
		return ExitUsage
	}
	store := StoreAt(dir)
	config, err := store.Load()
	if errors.Is(err, ErrNotEnrolled) {
		fmt.Fprintf(stdout, "配置：未注册（配置路径 %s）\n", store.Path())
	} else if err != nil {
		fmt.Fprintf(stdout, "配置：读取失败：%s\n", applog.RedactText(err.Error()))
	} else {
		fmt.Fprintf(stdout, "配置：device_id=%s name=%s platform=%s app_version=%s\n", config.DeviceID, config.Name, config.Platform, config.AppVersion)
		fmt.Fprintf(stdout, "接入地址：当前=%s 已配置=%d metrics_interval=%ds desired_autostart=%t terminal=%s\n",
			applog.RedactText(orNone(config.CurrentURL)), len(config.BaseURLs), config.MetricsIntervalMS/1000, config.DesiredAutostart, enabledText(config.TerminalEnabled))
	}
	if since, waiting := ReadOwnerWait(dir); waiting {
		fmt.Fprintf(stdout, "状态: 所属账号暂不可用，正在等待恢复 (自 %s)\n", since.Local().Format(time.RFC3339))
	}
	manager := cliNewManager(getenv)
	ctx, cancel := context.WithTimeout(context.Background(), cliTimeout)
	defer cancel()
	status := manager.Status(ctx)
	fmt.Fprintf(stdout, "服务：installed=%t enabled=%t active=%t\n", status.Installed, status.Enabled, status.Active)
	if status.LastError != "" {
		fmt.Fprintf(stdout, "服务错误：%s\n", applog.RedactText(status.LastError))
	}
	printServiceEnvironment(stdout, manager)
	printRuntimeShell(stdout, dir, getenv, 8*time.Second)
	stateDir := filepath.Join(dir, "durable", "supervisor")
	if endpoint, err := supervisor.HelperEndpoint(stateDir); err == nil {
		probeCtx, probeCancel := context.WithTimeout(ctx, 3*time.Second)
		_, probeErr := supervisor.NewClient(endpoint, stateDir).List(probeCtx)
		probeCancel()
		if probeErr != nil {
			fmt.Fprintf(stdout, "持久终端组件：未运行（%s）\n", applog.RedactText(probeErr.Error()))
		} else {
			fmt.Fprintf(stdout, "持久终端组件：正常（%s）\n", endpoint)
		}
	}
	collector := NewCollector(dir, time.Now)
	if _, err := collector.Collect(); err != nil {
		fmt.Fprintf(stdout, "指标采集：不可用（%s）\n", applog.RedactText(err.Error()))
	} else {
		fmt.Fprintln(stdout, "指标采集：正常")
	}
	return ExitOK
}

func printServerError(stderr io.Writer, prefix string, err error) {
	var serverError *ServerError
	if errors.As(err, &serverError) {
		fmt.Fprintf(stderr, "agent: %s: %s\n", prefix, applog.RedactText(serverError.Message))
		return
	}
	fmt.Fprintf(stderr, "agent: %s: %s\n", prefix, applog.RedactText(err.Error()))
}

func printCLIError(stderr io.Writer, prefix string, err error) {
	fmt.Fprintln(stderr, prefix, applog.RedactText(err.Error()))
}

func mustHomeDir() string {
	home, err := os.UserHomeDir()
	if err != nil {
		return ""
	}
	return home
}

func enabledText(enabled bool) string {
	if enabled {
		return "开启"
	}
	return "关闭"
}

func orNone(value string) string {
	if value == "" {
		return "无"
	}
	return value
}

func printServiceEnvironment(stdout io.Writer, manager ServiceManager) {
	reporter, ok := manager.(EnvironmentReporter)
	if !ok {
		return
	}
	env, installed := reporter.RecordedEnvironment()
	if !installed {
		return
	}
	for _, line := range env.describe() {
		fmt.Fprintln(stdout, applog.RedactText(line))
	}
}
