package agent

import (
	"context"
	"errors"
	"fmt"
	"os/exec"
	"strings"
)

// ServiceManager installs and inspects the autostart service for the agent:
// a per-user systemd unit, a launchd agent, or a Windows scheduled task.
// Implementations must report honestly when the service manager is
// unavailable (for example no user systemd bus): Installed reflects the unit
// file on disk while Enabled/Active stay false and LastError explains why.
type ServiceManager interface {
	Install(ctx context.Context, executable, dataDir string) error
	Uninstall(ctx context.Context) error
	Status(ctx context.Context) ServiceState
}

type CommandRunner interface {
	Run(ctx context.Context, name string, args ...string) (string, error)
}

type execRunner struct{}

func (execRunner) Run(ctx context.Context, name string, args ...string) (string, error) {
	command := exec.CommandContext(ctx, name, args...)
	output, err := command.CombinedOutput()
	if err != nil {
		var exitError *exec.ExitError
		if errors.As(err, &exitError) {
			return string(output), err
		}
		return string(output), fmt.Errorf("%s unavailable: %w", name, err)
	}
	return string(output), nil
}

func NewServiceManager(goos string, runner CommandRunner, getenv func(string) string, homeDir string) ServiceManager {
	return NewServiceManagerWithPrefix(goos, runner, getenv, homeDir, nil)
}

// NewServiceManagerWithPrefix is the same as NewServiceManager, except the service command generated by install
// inserts commandPrefix between the executable and run (e.g. the nexterm-server embedded distribution passes
// ["agent"], so the service runs `<server> agent run --data-dir ...`).
func NewServiceManagerWithPrefix(goos string, runner CommandRunner, getenv func(string) string, homeDir string, commandPrefix []string) ServiceManager {
	if runner == nil {
		runner = execRunner{}
	}
	if getenv == nil {
		getenv = func(string) string { return "" }
	}
	switch goos {
	case "linux":
		return newSystemdManager(runner, getenv, homeDir, commandPrefix...)
	case "darwin":
		return newLaunchdManagerEnv(runner, getenv, homeDir, launchdUID(), commandPrefix...)
	case "windows":
		return newWindowsManager(runner, commandPrefix...)
	default:
		return unsupportedManager{}
	}
}

type unsupportedManager struct{}

func (unsupportedManager) Install(context.Context, string, string) error {
	return ErrServiceUnsupported
}

func (unsupportedManager) Uninstall(context.Context) error {
	return ErrServiceUnsupported
}

func (unsupportedManager) Status(context.Context) ServiceState {
	return ServiceState{LastError: ErrServiceUnsupported.Error()}
}

// EmbeddedServiceManager is the service manager of an agent that runs inside
// another application, such as the desktop app exposing its local helper. It
// installs nothing and reports a clean, uninstalled service.
func EmbeddedServiceManager() ServiceManager { return embeddedManager{} }

type embeddedManager struct{}

func (embeddedManager) Install(context.Context, string, string) error {
	return ErrServiceUnsupported
}

func (embeddedManager) Uninstall(context.Context) error { return nil }

func (embeddedManager) Status(context.Context) ServiceState { return ServiceState{} }

func trimOutput(output string) string {
	return strings.TrimSpace(string(output))
}
