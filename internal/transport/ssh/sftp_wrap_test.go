package ssh

import (
	"reflect"
	"runtime"
	"testing"

	sshfs "github.com/Hello-CTF/NexTerm/internal/fs/ssh"
)

// TestSFTPFileSystemWrapsEveryPathMethod guards the Windows path mapping: a path-taking method of the embedded
// *sshfs.FS that sftpFileSystem does not define itself is promoted unchanged and receives an unmapped C:\ path.
func TestSFTPFileSystemWrapsEveryPathMethod(t *testing.T) {
	inner := reflect.TypeOf((*sshfs.FS)(nil))
	outer := reflect.TypeOf((*sftpFileSystem)(nil))
	stringType := reflect.TypeOf("")
	checked := 0
	for index := 0; index < inner.NumMethod(); index++ {
		method := inner.Method(index)
		takesPath := false
		for param := 1; param < method.Type.NumIn(); param++ {
			if method.Type.In(param) == stringType {
				takesPath = true
				break
			}
		}
		if !takesPath {
			continue
		}
		checked++
		wrapper, ok := outer.MethodByName(method.Name)
		if !ok {
			t.Errorf("sftpFileSystem lacks %s", method.Name)
			continue
		}
		function := runtime.FuncForPC(wrapper.Func.Pointer())
		if function == nil {
			t.Errorf("%s: no function metadata", method.Name)
			continue
		}
		if file, _ := function.FileLine(function.Entry()); file == "<autogenerated>" {
			t.Errorf("sftpFileSystem.%s is promoted from *sshfs.FS without Windows path mapping", method.Name)
		}
	}
	if checked < 10 {
		t.Fatalf("checked %d path methods; the reflection walk is not seeing *sshfs.FS", checked)
	}
}
