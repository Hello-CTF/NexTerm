CREATE OR REPLACE FUNCTION sync_tombstone_delete() RETURNS trigger AS $$
BEGIN
  INSERT INTO sync_tombstone(id, kind, deleted_at, owner_id)
  VALUES (OLD.id, TG_ARGV[0], (EXTRACT(EPOCH FROM clock_timestamp()) * 1000)::bigint, OLD.owner_id)
  ON CONFLICT(owner_id, id) DO NOTHING;
  RETURN OLD;
END;
$$ LANGUAGE plpgsql;

