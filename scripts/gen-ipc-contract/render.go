package main

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
)

type renderedCommand struct {
	contract commandContract
	input    typeRef
	output   typeRef
}

type jsonManifest struct {
	SchemaVersion  int                    `json:"schemaVersion"`
	DeferredScopes []string               `json:"deferredScopes"`
	Commands       map[string]jsonCommand `json:"commands"`
	LegacyCommands []string               `json:"legacyCommands"`
}

type jsonCommand struct {
	Scope   string `json:"scope,omitempty"`
	Nested  bool   `json:"nested"`
	Channel bool   `json:"channel"`
	Stream  string `json:"stream"`
}

func renderContracts(commands []commandContract, events []eventTopic) (map[string][]byte, error) {
	registry := newTypeRegistry()
	rendered := make([]renderedCommand, 0, len(commands))
	for _, command := range commands {
		if command.Input == nil {
			rendered = append(rendered, renderedCommand{contract: command})
			continue
		}
		input, err := registry.ref(command.Input)
		if err != nil {
			return nil, fmt.Errorf("map %s input: %w", command.Name, err)
		}
		output, err := registry.ref(command.Output)
		if err != nil {
			return nil, fmt.Errorf("map %s output: %w", command.Name, err)
		}
		rendered = append(rendered, renderedCommand{contract: command, input: input, output: output})
	}

	var manifest strings.Builder
	manifest.WriteString("// Code generated by go run ./scripts/gen-ipc-contract; DO NOT EDIT.\n\n")
	manifest.WriteString("import type * as contractTypes from \"./types\";\n\n")
	manifest.WriteString("export const ipcContractManifest = {\n  schemaVersion: 1,\n  deferredScopes: [")
	for index, scope := range deferredScopes() {
		if index > 0 {
			manifest.WriteString(", ")
		}
		manifest.WriteString(strconv.Quote(scope))
	}
	manifest.WriteString("] as const,\n  commands: {\n")
	for _, command := range rendered {
		fmt.Fprintf(&manifest, "    %s: {\n", strconv.Quote(command.contract.Name))
		if command.contract.Scope != "" {
			fmt.Fprintf(&manifest, "      scope: %s,\n", strconv.Quote(command.contract.Scope))
		}
		fmt.Fprintf(&manifest, "      nested: %t,\n", command.contract.Nested)
		fmt.Fprintf(&manifest, "      channel: %t,\n", command.contract.Channel)
		fmt.Fprintf(&manifest, "      stream: %s,\n", strconv.Quote(command.contract.Stream))
		if command.contract.Input != nil {
			if command.contract.Stream != "none" {
				manifest.WriteString("      streamPayload: \"unknown\",\n")
			}
			fmt.Fprintf(&manifest, "      input: { go: %s, ts: %s },\n", strconv.Quote(command.input.Go), strconv.Quote(command.input.TS))
			fmt.Fprintf(&manifest, "      output: { go: %s, ts: %s },\n", strconv.Quote(command.output.Go), strconv.Quote(command.output.TS))
		}
		manifest.WriteString("    },\n")
	}
	manifest.WriteString("  },\n  legacyCommands: [\n")
	for _, command := range rendered {
		if command.contract.Input == nil {
			fmt.Fprintf(&manifest, "    %s,\n", strconv.Quote(command.contract.Name))
		}
	}
	manifest.WriteString("  ] as const,\n} as const;\n\n")
	manifest.WriteString("export type IPCLegacyCommandName = (typeof ipcContractManifest.legacyCommands)[number];\n")
	manifest.WriteString("export type IPCTypedCommandName = Exclude<keyof typeof ipcContractManifest.commands, IPCLegacyCommandName>;\n")
	manifest.WriteString("export type IPCCommandName = keyof typeof ipcContractManifest.commands;\n\n")
	manifest.WriteString("export interface IPCCommandTypeMap {\n")
	for _, command := range rendered {
		if command.contract.Input == nil {
			continue
		}
		fmt.Fprintf(&manifest, "  %s: {\n", strconv.Quote(command.contract.Name))
		fmt.Fprintf(&manifest, "    input: %s;\n", manifestType(command.input))
		fmt.Fprintf(&manifest, "    output: %s;\n", manifestType(command.output))
		manifest.WriteString("  };\n")
	}
	manifest.WriteString("}\n\n")
	manifest.WriteString("export type IPCInput<Command extends IPCTypedCommandName> = IPCCommandTypeMap[Command][\"input\"];\n")
	manifest.WriteString("export type IPCOutput<Command extends IPCTypedCommandName> = IPCCommandTypeMap[Command][\"output\"];\n")

	var eventManifest strings.Builder
	eventManifest.WriteString("// Code generated by go run ./scripts/gen-ipc-contract; DO NOT EDIT.\n\n")
	eventManifest.WriteString("export const ipcEventTopics = {\n")
	for _, event := range events {
		fmt.Fprintf(&eventManifest, "  %s: %s,\n", strconv.Quote(event.Key), strconv.Quote(event.Topic))
	}
	eventManifest.WriteString("} as const;\n\n")
	eventManifest.WriteString("export type IPCEventTopic = (typeof ipcEventTopics)[keyof typeof ipcEventTopics];\n")

	jsonCommands := make(map[string]jsonCommand, len(commands))
	legacyCommands := make([]string, 0)
	for _, command := range commands {
		jsonCommands[command.Name] = jsonCommand{
			Scope: command.Scope, Nested: command.Nested, Channel: command.Channel, Stream: command.Stream,
		}
		if command.Input == nil {
			legacyCommands = append(legacyCommands, command.Name)
		}
	}
	manifestJSON, err := json.MarshalIndent(jsonManifest{
		SchemaVersion: 1, DeferredScopes: deferredScopes(), Commands: jsonCommands, LegacyCommands: legacyCommands,
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	manifestJSON = append(manifestJSON, '\n')

	return map[string][]byte{
		"events.ts":     []byte(eventManifest.String()),
		"manifest.json": manifestJSON,
		"manifest.ts":   []byte(manifest.String()),
		"types.ts":      []byte(registry.render()),
	}, nil
}

func manifestType(reference typeRef) string {
	return reference.Manifest
}

func deferredScopes() []string {
	var names []string
	for _, scope := range contractScopes {
		if scope.deferred {
			names = append(names, scope.name)
		}
	}
	return names
}
